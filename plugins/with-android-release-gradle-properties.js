const {
  withAppBuildGradle,
  withGradleProperties,
} = require("@expo/config-plugins");

const RELEASE_GRADLE_PROPERTIES = {
  "android.enableMinifyInReleaseBuilds": "true",
  "android.enableShrinkResourcesInReleaseBuilds": "true",
  "org.gradle.jvmargs": "-Xmx4096m -XX:MaxMetaspaceSize=1024m",
};

function upsertProperty(properties, key, value) {
  const existing = properties.find(
    (property) => property.type === "property" && property.key === key,
  );

  if (existing) {
    existing.value = value;
  } else {
    properties.push({ type: "property", key, value });
  }

  return properties;
}

const RELEASE_SIGNING_VARIABLES = `
// @generated by with-android-release-gradle-properties
def releaseStoreFile = findProperty('LOGMAXXING_UPLOAD_STORE_FILE') ?: System.getenv('LOGMAXXING_UPLOAD_STORE_FILE')
def releaseStorePassword = findProperty('LOGMAXXING_UPLOAD_STORE_PASSWORD') ?: System.getenv('LOGMAXXING_UPLOAD_STORE_PASSWORD')
def releaseKeyAlias = findProperty('LOGMAXXING_UPLOAD_KEY_ALIAS') ?: System.getenv('LOGMAXXING_UPLOAD_KEY_ALIAS')
def releaseKeyPassword = findProperty('LOGMAXXING_UPLOAD_KEY_PASSWORD') ?: System.getenv('LOGMAXXING_UPLOAD_KEY_PASSWORD')
def hasReleaseSigningConfig = releaseStoreFile && releaseStorePassword && releaseKeyAlias && releaseKeyPassword
`;

const RELEASE_SIGNING_CONFIG = `
        release {
            if (hasReleaseSigningConfig) {
                storeFile file(releaseStoreFile)
                storePassword releaseStorePassword
                keyAlias releaseKeyAlias
                keyPassword releaseKeyPassword
            }
        }`;

const RELEASE_BUILD_SIGNING = `            if (hasReleaseSigningConfig) {
                signingConfig signingConfigs.release
            }`;

function findGradleBlock(contents, blockName, startIndex = 0) {
  const blockPattern = new RegExp(`\\b${blockName}\\s*\\{`, "g");
  blockPattern.lastIndex = startIndex;
  const match = blockPattern.exec(contents);

  if (!match) {
    return null;
  }

  const openingBrace = contents.indexOf("{", match.index);
  let depth = 0;

  for (let index = openingBrace; index < contents.length; index += 1) {
    if (contents[index] === "{") {
      depth += 1;
    } else if (contents[index] === "}") {
      depth -= 1;
      if (depth === 0) {
        return {
          start: match.index,
          openingBrace,
          end: index + 1,
        };
      }
    }
  }

  return null;
}

function patchAppBuildGradle(contents) {
  if (contents.includes("def releaseStoreFile = findProperty('LOGMAXXING_UPLOAD_STORE_FILE')")) {
    return contents;
  }

  let next = contents.replace(
    /(def enableMinifyInReleaseBuilds[^\n]*\n)/,
    `$1${RELEASE_SIGNING_VARIABLES}\n`,
  );

  if (next === contents) {
    throw new Error(
      "Could not add Android release signing variables to app/build.gradle.",
    );
  }

  const signingConfigsBlock = findGradleBlock(next, "signingConfigs");
  const debugSigningBlock = signingConfigsBlock
    ? findGradleBlock(next, "debug", signingConfigsBlock.openingBrace + 1)
    : null;

  if (
    !signingConfigsBlock ||
    !debugSigningBlock ||
    debugSigningBlock.end > signingConfigsBlock.end
  ) {
    throw new Error(
      "Could not find the Android signing configs in app/build.gradle.",
    );
  }

  next =
    next.slice(0, debugSigningBlock.end) +
    RELEASE_SIGNING_CONFIG +
    next.slice(debugSigningBlock.end);

  const buildTypesBlock = findGradleBlock(next, "buildTypes");
  const releaseBuildBlock = buildTypesBlock
    ? findGradleBlock(next, "release", buildTypesBlock.openingBrace + 1)
    : null;

  if (
    !buildTypesBlock ||
    !releaseBuildBlock ||
    releaseBuildBlock.end > buildTypesBlock.end
  ) {
    throw new Error(
      "Could not find the Android release build type in app/build.gradle.",
    );
  }

  const releaseBuildContents = next.slice(
    releaseBuildBlock.start,
    releaseBuildBlock.end,
  );
  const patchedReleaseBuild = releaseBuildContents.includes(
    "signingConfig signingConfigs.debug",
  )
    ? releaseBuildContents.replace(
        /^\s*signingConfig signingConfigs\.debug\s*$/m,
        RELEASE_BUILD_SIGNING,
      )
    : releaseBuildContents.replace(
        /(release\s*\{\n)/,
        `$1${RELEASE_BUILD_SIGNING}\n`,
      );

  return (
    next.slice(0, releaseBuildBlock.start) +
    patchedReleaseBuild +
    next.slice(releaseBuildBlock.end)
  );
}

function verifyPatchedBuildGradle(contents) {
  const requiredFragments = [
    "def releaseStoreFile = findProperty('LOGMAXXING_UPLOAD_STORE_FILE')",
    "releaseStoreFile && releaseStorePassword && releaseKeyAlias && releaseKeyPassword",
    "signingConfig signingConfigs.release",
  ];

  for (const fragment of requiredFragments) {
    if (!contents.includes(fragment)) {
      throw new Error(
        `Android release signing patch is missing: ${fragment}`,
      );
    }
  }

  if (
    contents.includes(
      "release {\n            if (hasReleaseSigningConfig) {\n                signingConfig signingConfigs.release\n            }\n            if (hasReleaseSigningConfig) {\n                storeFile",
    )
  ) {
    throw new Error(
      "Android release build signing was inserted into signingConfigs.release.",
    );
  }

  return contents;
}

module.exports = function withAndroidReleaseGradleProperties(config) {
  let nextConfig = withGradleProperties(config, (modConfig) => {
    for (const [key, value] of Object.entries(RELEASE_GRADLE_PROPERTIES)) {
      upsertProperty(modConfig.modResults, key, value);
    }

    return modConfig;
  });

  nextConfig = withAppBuildGradle(nextConfig, (modConfig) => {
    modConfig.modResults.contents = verifyPatchedBuildGradle(
      patchAppBuildGradle(modConfig.modResults.contents),
    );
    return modConfig;
  });

  return nextConfig;
};

module.exports.upsertProperty = upsertProperty;
module.exports.patchAppBuildGradle = patchAppBuildGradle;
module.exports.verifyPatchedBuildGradle = verifyPatchedBuildGradle;
